CREATE TABLE prompt_templates (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(26) NOT NULL,
    template_key VARCHAR(80) NOT NULL,
    version_no INT UNSIGNED NOT NULL,
    display_name VARCHAR(160) NOT NULL,
    system_prompt MEDIUMTEXT NOT NULL,
    input_schema_version VARCHAR(80) NOT NULL,
    output_schema_version VARCHAR(80) NOT NULL,
    prompt_hash CHAR(64) NOT NULL,
    active TINYINT(1) NOT NULL DEFAULT 0,
    created_by VARCHAR(40) NOT NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    deleted_at DATETIME(3) NULL,
    active_template_key VARCHAR(80) GENERATED ALWAYS AS
        (CASE WHEN active = 1 AND deleted_at IS NULL THEN template_key ELSE NULL END) STORED,
    version INT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_prompt_templates_public_id (public_id),
    UNIQUE KEY uk_prompt_templates_key_version (template_key, version_no),
    UNIQUE KEY uk_prompt_templates_active (active_template_key),
    KEY idx_prompt_templates_key_time (template_key, created_at DESC),
    CONSTRAINT chk_prompt_templates_active CHECK (active IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE candidate_evidence_items (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(26) NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    evidence_key VARCHAR(240) NOT NULL,
    evidence_type VARCHAR(40) NOT NULL,
    source_type VARCHAR(40) NOT NULL,
    source_public_id CHAR(26) NOT NULL,
    field_path VARCHAR(160) NOT NULL,
    value_json JSON NOT NULL,
    normalized_text TEXT NOT NULL,
    content_hash CHAR(64) NOT NULL,
    version_no INT UNSIGNED NOT NULL,
    created_at DATETIME(3) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_candidate_evidence_public_id (public_id),
    UNIQUE KEY uk_candidate_evidence_version (user_id, evidence_key, version_no),
    UNIQUE KEY uk_candidate_evidence_hash (user_id, evidence_key, content_hash),
    KEY idx_candidate_evidence_user_type (user_id, evidence_type, created_at DESC),
    CONSTRAINT fk_candidate_evidence_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_candidate_evidence_type CHECK (evidence_type IN
        ('PROFILE','EDUCATION','EXPERIENCE','PROJECT','SKILL','RESUME_SECTION'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

