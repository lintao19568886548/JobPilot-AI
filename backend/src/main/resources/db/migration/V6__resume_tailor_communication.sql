CREATE TABLE resume_tailor_changes (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(26) NOT NULL,
    tailor_run_id BIGINT UNSIGNED NOT NULL,
    section_type VARCHAR(32) NOT NULL,
    operation VARCHAR(32) NOT NULL,
    before_text TEXT NULL,
    after_text TEXT NOT NULL,
    reason_text VARCHAR(1000) NOT NULL,
    evidence_refs_json JSON NOT NULL,
    sort_order INT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_resume_tailor_changes_public_id (public_id),
    KEY idx_resume_tailor_changes_run_sort (tailor_run_id, sort_order, id),
    CONSTRAINT fk_resume_tailor_changes_run FOREIGN KEY (tailor_run_id) REFERENCES resume_tailor_runs (id) ON DELETE RESTRICT,
    CONSTRAINT chk_resume_tailor_changes_section CHECK (section_type IN
        ('BASIC_INFO','SUMMARY','EDUCATION','SKILLS','EXPERIENCE','PROJECTS','CERTIFICATIONS','AWARDS','OPEN_SOURCE','OTHER')),
    CONSTRAINT chk_resume_tailor_changes_operation CHECK (operation IN ('SELECT','REORDER','REWRITE','COMPRESS','ATS_KEYWORD'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

