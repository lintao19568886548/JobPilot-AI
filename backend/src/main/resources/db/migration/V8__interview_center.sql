CREATE TABLE interviews (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(26) NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    application_id BIGINT UNSIGNED NULL,
    job_id BIGINT UNSIGNED NULL,
    company_id BIGINT UNSIGNED NULL,
    resume_version_id BIGINT UNSIGNED NULL,
    company_name_snapshot VARCHAR(200) NOT NULL,
    role_snapshot VARCHAR(200) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'SCHEDULED',
    result VARCHAR(24) NULL,
    timezone VARCHAR(64) NOT NULL,
    notes VARCHAR(4000) NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    deleted_at DATETIME(3) NULL,
    version INT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_interviews_public_id (public_id),
    KEY idx_interviews_user_status_time (user_id, status, updated_at DESC, id DESC),
    KEY idx_interviews_application (application_id),
    KEY idx_interviews_job (job_id),
    CONSTRAINT fk_interviews_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_interviews_application FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE RESTRICT,
    CONSTRAINT fk_interviews_job FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE RESTRICT,
    CONSTRAINT fk_interviews_company FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_interviews_resume FOREIGN KEY (resume_version_id) REFERENCES resume_versions (id) ON DELETE RESTRICT,
    CONSTRAINT chk_interviews_status CHECK (status IN ('SCHEDULED','IN_PROGRESS','COMPLETED','CANCELLED','NO_SHOW')),
    CONSTRAINT chk_interviews_result CHECK (result IS NULL OR result IN ('PENDING','PASSED','FAILED','MIXED','WITHDRAWN'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE interview_rounds (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(26) NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    interview_id BIGINT UNSIGNED NOT NULL,
    round_no INT UNSIGNED NOT NULL,
    round_type VARCHAR(32) NOT NULL,
    title VARCHAR(160) NOT NULL,
    scheduled_start_at DATETIME(3) NOT NULL,
    scheduled_end_at DATETIME(3) NOT NULL,
    timezone VARCHAR(64) NOT NULL,
    format VARCHAR(24) NOT NULL,
    meeting_link VARCHAR(1000) NULL,
    location VARCHAR(300) NULL,
    interviewer_name VARCHAR(160) NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PLANNED',
    result VARCHAR(24) NULL,
    notes VARCHAR(4000) NULL,
    completed_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    deleted_at DATETIME(3) NULL,
    active_round_no INT GENERATED ALWAYS AS (CASE WHEN deleted_at IS NULL THEN round_no ELSE NULL END) STORED,
    version INT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_interview_rounds_public_id (public_id),
    UNIQUE KEY uk_interview_rounds_number (interview_id, active_round_no),
    KEY idx_interview_rounds_user_time (user_id, scheduled_start_at, status),
    KEY idx_interview_rounds_interview_time (interview_id, scheduled_start_at, id),
    CONSTRAINT fk_interview_rounds_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_interview_rounds_interview FOREIGN KEY (interview_id) REFERENCES interviews (id) ON DELETE RESTRICT,
    CONSTRAINT chk_interview_rounds_order CHECK (round_no BETWEEN 1 AND 100),
    CONSTRAINT chk_interview_rounds_time CHECK (scheduled_end_at > scheduled_start_at),
    CONSTRAINT chk_interview_rounds_type CHECK (round_type IN ('PHONE_SCREEN','TECHNICAL','SYSTEM_DESIGN','BEHAVIORAL','HR','MANAGER','FINAL','OTHER')),
    CONSTRAINT chk_interview_rounds_format CHECK (format IN ('ONLINE','ONSITE','PHONE','OTHER')),
    CONSTRAINT chk_interview_rounds_status CHECK (status IN ('PLANNED','COMPLETED','CANCELLED')),
    CONSTRAINT chk_interview_rounds_result CHECK (result IS NULL OR result IN ('PENDING','PASSED','FAILED','MIXED','WITHDRAWN'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

