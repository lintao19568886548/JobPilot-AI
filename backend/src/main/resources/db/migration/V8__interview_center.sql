CREATE TABLE knowledge_gaps (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(26) NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    source_interview_id BIGINT UNSIGNED NOT NULL,
    source_review_id BIGINT UNSIGNED NOT NULL,
    source_review_item_id BIGINT UNSIGNED NULL,
    title VARCHAR(240) NOT NULL,
    category VARCHAR(80) NOT NULL,
    description_text VARCHAR(4000) NOT NULL,
    severity VARCHAR(16) NOT NULL,
    evidence_json JSON NOT NULL,
    recommended_actions_json JSON NOT NULL,
