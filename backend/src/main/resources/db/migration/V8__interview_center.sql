CREATE TABLE interview_reminders (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(26) NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    interview_id BIGINT UNSIGNED NOT NULL,
    round_id BIGINT UNSIGNED NULL,
    reminder_type VARCHAR(32) NOT NULL,
    title VARCHAR(240) NOT NULL,
    remind_at DATETIME(3) NOT NULL,
    timezone VARCHAR(64) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    completed_at DATETIME(3) NULL,
    cancelled_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    deleted_at DATETIME(3) NULL,
    round_dedup_id BIGINT UNSIGNED GENERATED ALWAYS AS (IFNULL(round_id, 0)) STORED,
    active_marker TINYINT GENERATED ALWAYS AS (CASE WHEN deleted_at IS NULL AND status = 'PENDING' THEN 1 ELSE NULL END) STORED,
    version INT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_interview_reminders_public_id (public_id),
    UNIQUE KEY uk_interview_reminders_active (interview_id, round_dedup_id, reminder_type, remind_at, active_marker),
    KEY idx_interview_reminders_user_due (user_id, status, remind_at, id),
    KEY idx_interview_reminders_interview (interview_id, status, remind_at),
    CONSTRAINT fk_interview_reminders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_interview_reminders_interview FOREIGN KEY (interview_id) REFERENCES interviews (id) ON DELETE RESTRICT,
    CONSTRAINT fk_interview_reminders_round FOREIGN KEY (round_id) REFERENCES interview_rounds (id) ON DELETE RESTRICT,
    CONSTRAINT chk_interview_reminders_type CHECK (reminder_type IN ('PREPARE','START','REVIEW','CUSTOM')),
    CONSTRAINT chk_interview_reminders_status CHECK (status IN ('PENDING','DONE','CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
