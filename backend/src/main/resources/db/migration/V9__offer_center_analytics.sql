CREATE TABLE offer_comparison_items (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(26) NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    comparison_id BIGINT UNSIGNED NOT NULL,
    offer_id BIGINT UNSIGNED NOT NULL,
    rank_no INT UNSIGNED NOT NULL,
    guaranteed_annual_cash DECIMAL(17,2) NOT NULL,
    potential_annual_cash DECIMAL(17,2) NULL,
    overall_score DECIMAL(7,2) NOT NULL,
    dimensions_json JSON NOT NULL,
    explanation_text VARCHAR(2000) NOT NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    deleted_at DATETIME(3) NULL,
    version INT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_offer_comparison_items_public_id (public_id),
    UNIQUE KEY uk_offer_comparison_item_offer (comparison_id, offer_id),
    KEY idx_offer_comparison_items_rank (comparison_id, rank_no, id),
    CONSTRAINT fk_offer_comparison_items_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_offer_comparison_items_comparison FOREIGN KEY (comparison_id) REFERENCES offer_comparisons (id) ON DELETE RESTRICT,
    CONSTRAINT fk_offer_comparison_items_offer FOREIGN KEY (offer_id) REFERENCES offers (id) ON DELETE RESTRICT,
    CONSTRAINT chk_offer_comparison_items_score CHECK (overall_score BETWEEN 0 AND 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE offer_deadlines (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(26) NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    offer_id BIGINT UNSIGNED NOT NULL,
    deadline_type VARCHAR(24) NOT NULL,
    title VARCHAR(240) NOT NULL,
    due_at DATETIME(3) NOT NULL,
    timezone VARCHAR(64) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    completed_at DATETIME(3) NULL,
    cancelled_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    deleted_at DATETIME(3) NULL,
    active_marker TINYINT GENERATED ALWAYS AS (CASE WHEN deleted_at IS NULL AND status='PENDING' THEN 1 ELSE NULL END) STORED,
    version INT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_offer_deadlines_public_id (public_id),
    UNIQUE KEY uk_offer_deadlines_active (offer_id, deadline_type, due_at, active_marker),
    KEY idx_offer_deadlines_user_due (user_id, status, due_at, id),
    CONSTRAINT fk_offer_deadlines_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_offer_deadlines_offer FOREIGN KEY (offer_id) REFERENCES offers (id) ON DELETE RESTRICT,
    CONSTRAINT chk_offer_deadlines_type CHECK (deadline_type IN ('DECISION','START','DOCUMENT','CUSTOM')),
    CONSTRAINT chk_offer_deadlines_status CHECK (status IN ('PENDING','DONE','CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

