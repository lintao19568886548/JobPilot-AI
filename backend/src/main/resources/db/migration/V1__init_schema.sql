    user_id BIGINT UNSIGNED NOT NULL,
    full_name VARCHAR(100) NULL,
    headline VARCHAR(160) NULL,
    phone VARCHAR(32) NULL,
    email VARCHAR(254) NULL,
    current_city VARCHAR(100) NULL,
