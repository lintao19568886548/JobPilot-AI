    CONSTRAINT fk_candidate_skills_profile FOREIGN KEY (candidate_profile_id) REFERENCES candidate_profiles (id) ON DELETE RESTRICT,
    CONSTRAINT fk_candidate_skills_skill FOREIGN KEY (skill_id) REFERENCES skills (id) ON DELETE RESTRICT,
    CONSTRAINT chk_candidate_skills_proficiency CHECK (proficiency BETWEEN 0 AND 100),
    CONSTRAINT chk_candidate_skills_years CHECK (years IS NULL OR years BETWEEN 0 AND 80)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE resumes (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(26) NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(160) NOT NULL,
    target_role VARCHAR(160) NULL,
    master TINYINT(1) NOT NULL DEFAULT 0,
    default_resume TINYINT(1) NOT NULL DEFAULT 0,
    description TEXT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    current_version_id BIGINT UNSIGNED NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    deleted_at DATETIME(3) NULL,
    active_master_user_id BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN master = 1 AND status = 'ACTIVE' AND deleted_at IS NULL THEN user_id ELSE NULL END) STORED,
    active_default_user_id BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN default_resume = 1 AND status = 'ACTIVE' AND deleted_at IS NULL THEN user_id ELSE NULL END) STORED,
    version INT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_resumes_public_id (public_id),
    UNIQUE KEY uk_resumes_active_master (active_master_user_id),
    UNIQUE KEY uk_resumes_active_default (active_default_user_id),
    KEY idx_resumes_user_status (user_id, deleted_at, status),
    KEY idx_resumes_current_version (current_version_id),
    CONSTRAINT fk_resumes_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_resumes_status CHECK (status IN ('DRAFT','ACTIVE','ARCHIVED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE resume_versions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(26) NOT NULL,
    resume_id BIGINT UNSIGNED NOT NULL,
    version_number INT UNSIGNED NOT NULL,
    version_name VARCHAR(160) NOT NULL,
    content_json JSON NOT NULL,
    rendered_text MEDIUMTEXT NULL,
    source_type VARCHAR(24) NOT NULL,
    created_by VARCHAR(40) NOT NULL,
    active TINYINT(1) NOT NULL DEFAULT 1,
    content_hash CHAR(64) NOT NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    deleted_at DATETIME(3) NULL,
    version INT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_resume_versions_public_id (public_id),
    UNIQUE KEY uk_resume_versions_number (resume_id, version_number),
    KEY idx_resume_versions_resume_time (resume_id, created_at DESC),
    CONSTRAINT fk_resume_versions_resume FOREIGN KEY (resume_id) REFERENCES resumes (id) ON DELETE RESTRICT,
    CONSTRAINT chk_resume_versions_source CHECK (source_type IN ('MANUAL','IMPORT','AI'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

